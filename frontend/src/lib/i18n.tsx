export type StringKey = keyof typeof STRINGS.en;

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: StringKey) => string }>({
  lang: "en", setLang: () => {}, t: (k) => STRINGS.en[k],
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try { return (localStorage.getItem("raahi.lang") as Lang) || "en"; } catch { return "en"; }
  });
  const set = (l: Lang) => { setLang(l); try { localStorage.setItem("raahi.lang", l); } catch { /* ignore */ } };
  return <LangCtx.Provider value={{ lang, setLang: set, t: (k) => STRINGS[lang][k] }}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx);
