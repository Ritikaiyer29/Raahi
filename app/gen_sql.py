"""Generate supabase/migrations/0001_init.sql from the SQLAlchemy models (Postgres dialect), with RLS enabled
and no anon/authenticated policies: only the backend (service role / direct connection) can read or write.
Run: python -m app.gen_sql"""
from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from . import models as m

OUT = Path(__file__).resolve().parent.parent / "supabase" / "migrations" / "0001_init.sql"


def main() -> None:
    d = postgresql.dialect()
    parts = ["-- Generated by `python -m app.gen_sql` from app/models.py. Do not edit by hand.",
             "create extension if not exists pgcrypto;", ""]
    for t in m.Base.metadata.sorted_tables:
        ddl = str(CreateTable(t, if_not_exists=True).compile(dialect=d)).strip()
        ddl = ddl.replace("id UUID NOT NULL,", "id UUID NOT NULL DEFAULT gen_random_uuid(),", 1)
        parts.append(ddl + ";")
        for ix in t.indexes:
            parts.append(str(CreateIndex(ix, if_not_exists=True).compile(dialect=d)).strip() + ";")
        parts.append(f"alter table public.{t.name} enable row level security;")
        parts.append(f"revoke all on public.{t.name} from anon, authenticated;")
        parts.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
